const cardGrid = document.getElementById("card-grid");
const homePage = document.getElementById("home-page");
const articlePage = document.getElementById("article-page");
const articleView = document.getElementById("article-view");
const backButton = document.getElementById("back-button");

const articleOrder = ["philippines", "baguio", "vigan"];

function renderCards() {
  cardGrid.innerHTML = "";

  articleOrder.forEach((key) => {
    const article = articles[key];
    const card = document.createElement("button");
    card.type = "button";
    card.className = "story-card";
    card.innerHTML = `
      <div class="story-thumb">
        <img src="${article.image}" alt="${article.tag} preview image" loading="lazy">
      </div>
      <div class="story-body">
        <span class="story-tag">${article.tag}</span>
        <h3>${article.title}</h3>
        <p>${article.teaser}</p>
      </div>
    `;
    card.addEventListener("click", () => {
      location.hash = article.slug;
    });
    cardGrid.appendChild(card);
  });
}

function renderArticle(slug) {
  const article = articles[slug];
  if (!article) {
    location.hash = "";
    return;
  }

  homePage.hidden = true;
  articlePage.hidden = false;

  const metaHtml = article.meta.length
    ? `<div class="article-meta">${article.meta
        .map((item) => `<span class="meta-chip"><strong>${item.label}:</strong> ${item.value}</span>`)
        .join("")}</div>`
    : "";

  articleView.innerHTML = `
    <figure class="article-hero">
      <img src="${article.image}" alt="${article.tag} article image" />
    </figure>
    <div class="article-meta-wrap">
      <p class="section-kicker">${article.category}</p>
      <h2 class="article-title">${article.title}</h2>
      <p class="article-meta">
        <span><strong>Author:</strong> ${article.author}</span>
      </p>
      ${metaHtml}
    </div>
    <p class="article-source">
      Main photo source:
      <a href="${article.sourceUrl}" target="_blank" rel="noreferrer">${article.sourceLabel}</a>
    </p>
    <div class="article-content">
      ${article.paragraphs.map((paragraph) => `<p>${paragraph}</p>`).join("")}
    </div>
  `;
}

function showHome() {
  homePage.hidden = false;
  articlePage.hidden = true;
}

function syncRoute() {
  const slug = location.hash.replace("#", "");
  if (!slug) {
    showHome();
    return;
  }

  if (!articles[slug]) {
    showHome();
    return;
  }

  renderArticle(slug);
}

backButton.addEventListener("click", () => {
  location.hash = "";
});

window.addEventListener("hashchange", syncRoute);

renderCards();
syncRoute();
